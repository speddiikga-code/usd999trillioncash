function schemaSql(spec: MvpSpec): string {
  const tables = spec.entities.map((en) => {
    const cols = en.fields.map((f) => {
      const check = f.type === 'email' ? ` CHECK (position('@' in ${ident(f.name)}) > 1)` : f.type === 'url' ? ` CHECK (${ident(f.name)} ~ '^https?://')` : '';
      return `  ${ident(f.name)} ${SQL_TYPES[f.type]}${f.required ? ' NOT NULL' : ''}${check}`;
    });
    return `CREATE TABLE ${ident(en.plural.replace(/-/g, '_'))} (\n  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),\n${cols.join(',\n')},\n  created_at timestamptz NOT NULL DEFAULT now(),\n  updated_at timestamptz NOT NULL DEFAULT now()\n);`;
  });
  return `-- ${spec.name}: PostgreSQL schema (generated by ${GENERATOR_VERSION}).
-- The MVP ships with a JSON-file store; apply this schema when moving to PostgreSQL.

CREATE TABLE signups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE CHECK (position('@' in email) > 1),
  name text,
  ref text,
  variant text,
  anonymous_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);

${tables.join('\n\n')}
`;
}

function openApi(spec: MvpSpec): string {
  const schemas: Record<string, unknown> = {};
  const paths: Record<string, unknown> = {
    '/health': { get: { summary: 'Health check', responses: { '200': { description: 'OK' } } } },
    '/api/signup': {
      post: {
        summary: 'Join the early-access list',
        requestBody: { required: true, content: { 'application/json': { schema: { type: 'object', required: ['email'], properties: { email: { type: 'string', format: 'email' }, name: { type: 'string' }, ref: { type: 'string' }, anonymousId: { type: 'string' }, variant: { type: 'string' } } } } } },
        responses: { '201': { description: 'Signed up' }, '400': { description: 'Invalid email' } },
      },
    },
    '/api/events': { post: { summary: 'Record a client funnel event', responses: { '202': { description: 'Accepted' } } } },
    '/api/checkout': { post: { summary: 'Start checkout (501 until a payment link is approved)', responses: { '200': { description: 'Payment URL' }, '501': { description: 'Payments not enabled' } } } },
  };
  for (const en of spec.entities) {
    schemas[en.name] = {
      type: 'object',
      required: en.fields.filter((f) => f.required).map((f) => f.name),
      properties: Object.fromEntries(en.fields.map((f) => [f.name, OAS_TYPES[f.type]])),
    };
    const ref = { $ref: `#/components/schemas/${en.name}` };
    paths[`/api/${en.plural}`] = {
      get: { summary: `List ${en.plural}`, responses: { '200': { description: 'OK' } } },
      post: { summary: `Create ${en.name}`, requestBody: { required: true, content: { 'application/json': { schema: ref } } }, responses: { '201': { description: 'Created' }, '400': { description: 'Validation failed' } } },
    };
    paths[`/api/${en.plural}/{id}`] = {
      parameters: [{ name: 'id', in: 'path', required: true, schema: { type: 'string' } }],
      get: { summary: `Get ${en.name}`, responses: { '200': { description: 'OK' }, '404': { description: 'Not found' } } },
      put: { summary: `Update ${en.name}`, requestBody: { content: { 'application/json': { schema: ref } } }, responses: { '200': { description: 'Updated' } } },
      delete: { summary: `Delete ${en.name}`, responses: { '204': { description: 'Deleted' } } },
    };
  }
  return JSON.stringify({ openapi: '3.1.0', info: { title: spec.name, version: '0.1.0', description: spec.valueProposition }, paths, components: { schemas } }, null, 2) + '\n';
}

function testFile(): string {
  // Generic test-suite driven by lib/spec.js — exercises every generated entity.
  return String.raw`import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from '../server.js';
import { SPEC } from '../lib/spec.js';

const SAMPLES = { string: 'Sample value', text: 'Some longer notes', number: 42, boolean: true, date: '2026-01-15', email: 'test@example.com', url: 'https://example.com/page' };
let server;
let base;

before(async () => {
  const dir = mkdtempSync(path.join(process.env.DATA_DIR || os.tmpdir(), 'mvp-test-'));
  server = createServer({ dataDir: dir });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  base = 'http://127.0.0.1:' + server.address().port;
});

after(() => new Promise((resolve) => server.close(resolve)));

const json = (method, p, body) => fetch(base + p, { method, headers: { 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });

test('health endpoint responds', async () => {
  const r = await fetch(base + '/health');
  assert.equal(r.status, 200);
  assert.equal((await r.json()).ok, true);
});

test('landing page is served with security headers and injected config', async () => {
  const r = await fetch(base + '/');
  assert.equal(r.status, 200);
  assert.match(r.headers.get('content-security-policy'), /default-src 'self'/);
  assert.equal(r.headers.get('x-frame-options'), 'DENY');
  const html = await r.text();
  assert.ok(!html.includes('__ROOS_CONFIG__'), 'config placeholder must be replaced');
  const cfg = JSON.parse(html.split('<script id="roos-config" type="application/json">')[1].split('</script>')[0]);
  assert.deepEqual(cfg.variants, SPEC.variants);
});

test('signup validates email addresses', async () => {
  assert.equal((await json('POST', '/api/signup', { email: 'not-an-email' })).status, 400);
  assert.equal((await json('POST', '/api/signup', { email: '<script>@x' })).status, 400);
  assert.equal((await json('POST', '/api/signup', { email: 'person@example.com', name: 'Pat' })).status, 201);
  const again = await json('POST', '/api/signup', { email: 'person@example.com' });
  assert.equal((await again.json()).duplicate, true);
});

test('rejects malformed and oversized bodies', async () => {
  const bad = await fetch(base + '/api/signup', { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{nope' });
  assert.equal(bad.status, 400);
  const big = await json('POST', '/api/signup', { email: 'a@b.co', name: 'x'.repeat(70000) });
  assert.equal(big.status, 413);
});

test('blocks path traversal on static files', async () => {
  assert.equal((await fetch(base + '/static/..%2Fserver.js')).status, 404);
  assert.equal((await fetch(base + '/static/../../server.js')).status, 404);
});

test('checkout is disabled until a payment link is approved', async () => {
  const r = await json('POST', '/api/checkout', { tier: SPEC.pricingTiers[0] && SPEC.pricingTiers[0].name });
  assert.equal(r.status, 501);
});

for (const entity of SPEC.entities) {
  test('CRUD for ' + entity.name, async () => {
    const payload = {};
    for (const f of entity.fields) payload[f.name] = SAMPLES[f.type];
    const created = await json('POST', '/api/' + entity.plural, payload);
    assert.equal(created.status, 201);
    const item = await created.json();
    assert.ok(item.id);
    const list = await (await fetch(base + '/api/' + entity.plural)).json();
    assert.ok(list.items.some((x) => x.id === item.id));
    const first = entity.fields[0];
    const upd = await json('PUT', '/api/' + entity.plural + '/' + item.id, { [first.name]: SAMPLES[first.type] });
    assert.equal(upd.status, 200);
    assert.equal((await json('DELETE', '/api/' + entity.plural + '/' + item.id)).status, 204);
    assert.equal((await fetch(base + '/api/' + entity.plural + '/' + item.id)).status, 404);
  });

  test('validation for ' + entity.name, async () => {
    const required = entity.fields.filter((f) => f.required);
    const r = await json('POST', '/api/' + entity.plural, {});
    assert.equal(r.status, required.length ? 400 : 201);
    const typed = entity.fields.find((f) => f.type === 'number' || f.type === 'email' || f.type === 'date');
    if (typed) {
      const payload = {};
      for (const f of entity.fields) payload[f.name] = SAMPLES[f.type];
      payload[typed.name] = 'definitely-invalid';
      assert.equal((await json('POST', '/api/' + entity.plural, payload)).status, 400);
    }
  });
}
`;
}

function dockerfile(): string {
  return `# Generated by ${GENERATOR_VERSION}
FROM node:24-alpine
WORKDIR /app
COPY --chown=node:node . .
RUN mkdir -p /data && chown node:node /data
USER node
ENV NODE_ENV=production HOST=0.0.0.0 PORT=3000 DATA_DIR=/data
EXPOSE 3000
HEALTHCHECK --interval=30s --timeout=3s CMD wget -qO- http://127.0.0.1:3000/health || exit 1
CMD ["node", "server.js"]
`;
}

