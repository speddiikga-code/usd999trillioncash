/** Produce every file of the MVP. Pure function — writing is done by `writeProject`. */
export function generateProject(spec: MvpSpec): GeneratedFile[] {
  const files: GeneratedFile[] = [
    {
      path: 'package.json',
      content:
        JSON.stringify(
          {
            name: spec.slug || 'mvp',
            version: '0.1.0',
            private: true,
            type: 'module',
            description: spec.tagline,
            engines: { node: '>=20' },
            scripts: { start: 'node server.js', test: 'node --test --test-isolation=none test/server.test.js' },
          },
          null,
          2,
        ) + '\n',
    },
    { path: 'server.js', content: SERVER_JS },
    { path: 'lib/spec.js', content: specModule(spec) },
    { path: 'lib/store.js', content: STORE_JS },
    { path: 'lib/validate.js', content: VALIDATE_JS },
    { path: 'lib/analytics.js', content: ANALYTICS_JS },
    { path: 'lib/payments.js', content: PAYMENTS_JS },
    { path: 'public/index.html', content: landingHtml(spec) },
    { path: 'public/app.html', content: appHtml(spec) },
    { path: 'public/landing.js', content: LANDING_JS },
    { path: 'public/app.js', content: APP_JS },
    { path: 'public/styles.css', content: STYLES_CSS },
    { path: 'schema.sql', content: schemaSql(spec) },
    { path: 'openapi.json', content: openApi(spec) },
    { path: 'test/server.test.js', content: testFile() },
    { path: 'Dockerfile', content: dockerfile() },
    { path: '.dockerignore', content: 'data\nnode_modules\n.env\n' },
    {
      path: 'docker-compose.yml',
      content: `services:\n  app:\n    build: .\n    ports:\n      - "127.0.0.1:3000:3000"\n    environment:\n      ROOS_TRACK_URL: \${ROOS_TRACK_URL:-}\n      ROOS_WRITE_KEY: \${ROOS_WRITE_KEY:-}\n      ROOS_EXPERIMENT_ID: \${ROOS_EXPERIMENT_ID:-}\n      PAYMENT_LINK_URL: \${PAYMENT_LINK_URL:-}\n    volumes:\n      - data:/data\n    read_only: true\n    tmpfs: [/tmp]\n    security_opt: [no-new-privileges:true]\n    cap_drop: [ALL]\nvolumes:\n  data: {}\n`,
    },
    {
      path: 'deploy/fly.toml',
      content: `# Example Fly.io config — deploying to production requires approval in ROOS.\napp = "${spec.slug || 'mvp'}"\n\n[build]\n  dockerfile = "../Dockerfile"\n\n[env]\n  PORT = "3000"\n  DATA_DIR = "/data"\n\n[[mounts]]\n  source = "data"\n  destination = "/data"\n\n[http_service]\n  internal_port = 3000\n  force_https = true\n\n  [[http_service.checks]]\n    grace_period = "10s"\n    interval = "30s"\n    method = "GET"\n    path = "/health"\n    timeout = "3s"\n`,
    },
    {
      path: 'deploy/README.md',
      content: `# Deploying ${spec.name}\n\n1. Approve the \`deploy.production\` request in the ROOS approval center.\n2. Build: \`docker build -t ${spec.slug || 'mvp'} .\`\n3. Run anywhere that runs containers, e.g. \`fly launch --config deploy/fly.toml\` or \`docker compose up -d\`.\n4. Set \`ROOS_TRACK_URL\`, \`ROOS_WRITE_KEY\` and \`ROOS_EXPERIMENT_ID\` so funnel events reach ROOS.\n5. Only set \`PAYMENT_LINK_URL\` after the \`billing.configure\` approval created the payment link.\n`,
    },
    { path: '.env.example', content: 'PORT=3000\nHOST=127.0.0.1\nDATA_DIR=./data\nROOS_TRACK_URL=http://localhost:4000/api/track\nROOS_WRITE_KEY=\nROOS_EXPERIMENT_ID=\nROOS_VARIANTS_JSON=\nPAYMENT_LINK_URL=\n' },
    { path: 'SPEC.md', content: specMd(spec) },
    { path: 'roos.json', content: JSON.stringify({ generator: GENERATOR_VERSION, provenance: spec.provenance, spec }, null, 2) + '\n' },
  ];
  files.push({ path: 'README.md', content: readme(spec, files.map((f) => f.path).concat('README.md')) });
  return files;
}
