const SQL_TYPES: Record<string, string> = { string: 'text', text: 'text', number: 'double precision', boolean: 'boolean', date: 'date', email: 'text', url: 'text' };
const OAS_TYPES: Record<string, Record<string, string>> = {
  string: { type: 'string', maxLength: '200' },
  text: { type: 'string', maxLength: '5000' },
  number: { type: 'number' },
  boolean: { type: 'boolean' },
  date: { type: 'string', format: 'date' },
  email: { type: 'string', format: 'email' },
  url: { type: 'string', format: 'uri' },
};
export const SAMPLE_VALUES: Record<string, unknown> = { string: 'Sample value', text: 'Some longer notes', number: 42, boolean: true, date: '2026-01-15', email: 'test@example.com', url: 'https://example.com/page' };

const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const ident = (s: string) => `"${snake(s).replace(/"/g, '')}"`;

function specModule(spec: MvpSpec): string {
  const runtime = { name: spec.name, tagline: spec.tagline, entities: spec.entities, pricingTiers: spec.pricingTiers, variants: spec.variants, headlines: spec.headlines };
  return `// Generated by ${GENERATOR_VERSION}. Runtime configuration for this MVP.\nexport const SPEC = ${JSON.stringify(runtime, null, 2)};\n`;
}

